"""Application-level errors (the class name doubles as an i18n key: err.<ClassName>)."""


class AppError(Exception):
    def __init__(self, message: str = "", **context):
        super().__init__(message or self.__class__.__name__)
        self.context = context


class ProductNotFound(AppError): ...
class SaleNotFound(AppError): ...
class UserNotFound(AppError): ...
class NotFound(AppError): ...
class DuplicateEntity(AppError): ...
class PermissionDenied(AppError): ...
class AuthenticationFailed(AppError): ...
class ApprovalRejected(AppError): ...
class ApprovalRequired(AppError): ...
class ParkedSalesExist(AppError): ...
class InvalidDateRange(AppError): ...
class InvalidInput(AppError): ...
class BackupError(AppError): ...
