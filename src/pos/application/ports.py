"""Ports: abstract interfaces owned by the application layer and implemented by adapters."""
from __future__ import annotations

from datetime import date, datetime
from decimal import Decimal
from pathlib import Path
from typing import Any, Optional, Protocol, Sequence

from ..domain.entities import AuditEntry, Category, Customer, Product, Shift, StockMovement, User
from ..domain.refund import Refund
from ..domain.sale import Sale
from .dto import BackupInfo, ShiftTotals


class ProductRepository(Protocol):
    def get(self, product_id: str) -> Optional[Product]: ...
    def get_by_barcode(self, barcode: str) -> Optional[Product]: ...
    def get_by_sku(self, sku: str) -> Optional[Product]: ...
    def search(self, query: str, limit: int = 50, include_inactive: bool = False) -> list[Product]: ...
    def save(self, product: Product) -> None: ...


class CategoryRepository(Protocol):
    def get(self, category_id: str) -> Optional[Category]: ...
    def list(self) -> list[Category]: ...
    def save(self, category: Category) -> None: ...


class SaleRepository(Protocol):
    def get(self, sale_id: str) -> Optional[Sale]: ...
    def find_by_number(self, number: int) -> Optional[Sale]: ...
    def save(self, sale: Sale) -> None: ...
    def next_number(self) -> int: ...
    def list_parked(self, shift_id: Optional[str] = None) -> list[Sale]: ...
    def mark_printed(self, sale_id: str, printed: bool) -> None: ...


class RefundRepository(Protocol):
    def save(self, refund: Refund) -> None: ...
    def list_for_sale(self, sale_id: str) -> list[Refund]: ...
    def next_number(self) -> int: ...


class ShiftRepository(Protocol):
    def get(self, shift_id: str) -> Optional[Shift]: ...
    def get_open(self) -> Optional[Shift]: ...
    def save(self, shift: Shift) -> None: ...


class CustomerRepository(Protocol):
    def get(self, customer_id: str) -> Optional[Customer]: ...
    def search(self, query: str, limit: int = 50) -> list[Customer]: ...
    def save(self, customer: Customer) -> None: ...


class UserRepository(Protocol):
    def get(self, user_id: str) -> Optional[User]: ...
    def get_by_username(self, username: str) -> Optional[User]: ...
    def list(self) -> list[User]: ...
    def save(self, user: User) -> None: ...


class StockLedger(Protocol):
    def append(self, movement: StockMovement) -> None: ...
    def on_hand(self, product_id: str) -> Decimal: ...
    def low_stock(self) -> list[tuple[Product, Decimal]]: ...


class AuditLog(Protocol):
    def append(self, entry: AuditEntry) -> None: ...
    def recent(self, limit: int = 200) -> list[AuditEntry]: ...


class SettingsRepository(Protocol):
    def get(self, key: str, default: str = "") -> str: ...
    def set(self, key: str, value: str) -> None: ...
    def all(self) -> dict[str, str]: ...


class UnitOfWork(Protocol):
    products: ProductRepository
    categories: CategoryRepository
    sales: SaleRepository
    refunds: RefundRepository
    shifts: ShiftRepository
    customers: CustomerRepository
    users: UserRepository
    stock: StockLedger
    audit: AuditLog
    settings: SettingsRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type, exc, tb) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class ReportQueries(Protocol):
    """Read-only, SQL-optimised queries returning plain rows."""
    def run(self, kind: str, date_from: date, date_to: date,
            cashier_id: Optional[str] = None) -> tuple[list[str], list[list], list]: ...
    def shift_totals(self, shift_id: str) -> ShiftTotals: ...


class ReceiptPrinter(Protocol):
    def print(self, document: Any) -> None: ...      # SaleReceipt | RefundReceipt | ZReport
    def open_drawer(self) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, secret: str) -> str: ...
    def verify(self, secret: str, hashed: str) -> bool: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdGenerator(Protocol):
    def new_id(self) -> str: ...


class BackupService(Protocol):
    def create(self, destination: Optional[Path] = None) -> BackupInfo: ...
    def restore(self, source: Path) -> None: ...
    def list(self) -> list[BackupInfo]: ...


class CsvExporter(Protocol):
    def write(self, path: Path, columns: Sequence[str], rows: Sequence[Sequence], totals: Sequence) -> None: ...
